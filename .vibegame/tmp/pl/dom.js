const out = {};
const q = (s) => document.querySelector(s);
out.hasBrokerShell = !!q('#broker-shell');
out.hasChapterRoot = !!q('#chapter-root');
out.gameContainerChildren = q('#game-container') ? Array.from(q('#game-container').children).map((e) => e.tagName + '.' + e.className + '#' + e.id) : null;
out.chapterRootHTML = q('#chapter-root') ? q('#chapter-root').outerHTML.slice(0, 1200) : null;
const panel = q('.ch-panel') || q('[class*=ch-open]') || q('.vg-menu-panel');
out.panelSel = panel ? panel.className : null;
out.gameContainerText = q('#game-container') ? q('#game-container').innerText.slice(0, 800) : null;
return out;
